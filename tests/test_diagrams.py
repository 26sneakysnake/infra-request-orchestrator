import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

from diagrams.bpmn_svg import DIAGRAMS, NS, render


@pytest.mark.parametrize(("bpmn", "svg"), DIAGRAMS)
def test_every_named_flow_node_is_drawn_and_the_image_is_up_to_date(bpmn: Path, svg: Path) -> None:
    image = render(bpmn)
    ET.fromstring(image)  # well-formed SVG
    process = ET.parse(bpmn).getroot().find(".//bpmn:process", NS)
    for element in process:
        name = element.get("name")
        if name and not element.tag.endswith(("sequenceFlow", "laneSet")):
            first_word = name.split()[0].replace("'", "&#x27;")
            assert first_word in image, f"{element.get('id')} ({name}) missing from {svg.name}"
    # docs/img is regenerated by `make diagrams`: a model change without it fails here.
    assert svg.read_text(encoding="utf-8") == image, f"run `make diagrams` to refresh {svg.name}"


def test_as_is_model_is_documentation_only() -> None:
    root = ET.parse(DIAGRAMS[1][0]).getroot()
    assert root.find(".//bpmn:process", NS).get("isExecutable") == "false"
    # Every step of the as-is model refers to a declared hypothesis (hypotheses/as-is.yaml).
    tasks = root.findall(".//bpmn:manualTask", NS)
    assert tasks and all("(AS-0" in t.get("name") for t in tasks)
